#!/usr/bin/env node
// Vendor the sightmap agent skills into this repo's skills/ directory.
//
// The sightmap-authoring and sightmap-browser skills are maintained in the
// sightmap repo (github.com/sightmap/sightmap) and shipped inside the published
// @sightmap/sightmap npm package. Subtext bundles them so a Subtext user gets
// them implicitly — no separate install, no binary required at install time.
//
// This is the vendoring pattern we want third parties to reuse:
//   1. add the source package as a pinned devDependency:
//        npm install --save-dev @sightmap/sightmap@<version>
//   2. run this script to copy its skills/sightmap-* directories into ./skills:
//        npm run vendor-skills
//   3. commit the result. The pinned version is the provenance; a marker file
//      (.sightmap-vendored.json) records exactly what was vendored.
//
// The copies under skills/sightmap-*/ are GENERATED — do not hand-edit them.
// Fix the source in the sightmap repo, publish, bump the pin, and re-run.
//
// Pure Node.js (no deps). Idempotent.

import { cpSync, existsSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SKILLS_DIR = join(REPO_ROOT, 'skills');
const SOURCE_PKG = '@sightmap/sightmap';
const PREFIX = 'sightmap-';

// Resolve the installed source package from this repo's node_modules.
const require = createRequire(import.meta.url);
let pkgJsonPath;
try {
  pkgJsonPath = require.resolve(`${SOURCE_PKG}/package.json`, { paths: [REPO_ROOT] });
} catch {
  console.error(
    `sync-sightmap-skills: ${SOURCE_PKG} is not installed.\n` +
      `Add it as a pinned devDependency and install first, e.g.:\n` +
      `  npm install --save-dev ${SOURCE_PKG}@<version>\n`,
  );
  process.exit(1);
}

const { version } = JSON.parse(readFileSync(pkgJsonPath, 'utf8'));
const srcSkills = join(dirname(pkgJsonPath), 'skills');
if (!existsSync(srcSkills)) {
  console.error(
    `sync-sightmap-skills: ${SOURCE_PKG}@${version} does not ship a skills/ directory.\n` +
      `Pin a version that includes the skills (0.14.0 or later).\n`,
  );
  process.exit(1);
}

const vendored = [];
for (const entry of readdirSync(srcSkills, { withFileTypes: true })) {
  if (!entry.isDirectory() || !entry.name.startsWith(PREFIX)) continue;
  const dest = join(SKILLS_DIR, entry.name);
  rmSync(dest, { recursive: true, force: true });
  cpSync(join(srcSkills, entry.name), dest, { recursive: true });
  vendored.push(entry.name);
  console.log(`vendor: ${entry.name} ← ${SOURCE_PKG}@${version}`);
}

if (vendored.length === 0) {
  console.error(`sync-sightmap-skills: no ${PREFIX}* skills found in ${SOURCE_PKG}@${version}.`);
  process.exit(1);
}

vendored.sort();
const marker = {
  source: SOURCE_PKG,
  version,
  skills: vendored,
  syncedAt: new Date().toISOString(),
  note: 'Generated by scripts/sync-sightmap-skills.mjs — do not hand-edit the vendored skills.',
};
writeFileSync(join(REPO_ROOT, '.sightmap-vendored.json'), JSON.stringify(marker, null, 2) + '\n');
console.log(`vendor: wrote .sightmap-vendored.json (${vendored.length} skill(s) @ ${version})`);
